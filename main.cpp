void resuelveCaso() {

    // leer los datos de la entrada
    int N, C, A, L, T;
    cin >> N >> C >> A >> L >> T;

    //creamos el grafo con N nodos
    Grafo g(N);

    //ponemos las aristas al grafo
    for (int i = 0; i < C; i++)
    {
        int a, b; cin >> a >> b;

        g.ponArista(a-1,b-1);
    }

    Tramo t(g, A-1, L-1, T-1);

    cout << t.tramoMasEficiente() << "\n";
}

