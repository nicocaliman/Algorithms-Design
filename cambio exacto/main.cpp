const int MAX_PAGAR = 20000;

void resuelveCaso() {

    // leer los datos de la entrada
    int precio, N; cin >> precio >> N;
    
    vector<int> billetes(N);

    for (int i = 0; i < N; i++)
    {
        cin >> billetes[i];
    }
        
    vector<EntInf> billetesNecesarios(MAX_PAGAR+1, Infinito);
    billetesNecesarios[0] = 0;

    for (int i = 1; i <= billetes.size(); i++)
    {
        for (int j = MAX_PAGAR; j >= billetes[i-1]; --j)
        {
            billetesNecesarios[j] = min(billetesNecesarios[j], billetesNecesarios[j - billetes[i - 1]] + 1);
        }
    }

    int pago = precio;
    while (pago <= MAX_PAGAR && billetesNecesarios[pago] == Infinito) {
        ++pago;
    }

    cout << pago << ' ' << billetesNecesarios[pago] << '\n';

}

