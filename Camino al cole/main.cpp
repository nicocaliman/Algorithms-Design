void resuelveCaso() {

    // leer los datos de la entrada
    int N, C; cin >> N >> C;
    
    GrafoValorado<int> grafo(N);

    for (int i = 0; i < C; i++)
    {
        int origen, destino, valor; cin >> origen >> destino >> valor;
        
        grafo.ponArista({origen-1, destino-1, valor});
    }

    Dijkstra<int> dijk(grafo, 0);

    cout << dijk.numCaminos(N-1) << "\n";
}

